BibleStory storyById(String id) =>
    bibleStories.firstWhere((story) => story.id == id);

List<BibleStory> storiesByTestament(Testament testament) =>
    bibleStories.where((story) => story.testament == testament).toList();

VocabWord? vocabWordById(String id) {
  for (final story in bibleStories) {
    for (final word in story.vocabulary) {
      if (word.id == id) return word;
    }
  }
  return null;
}

